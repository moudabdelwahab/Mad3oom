-- ============================================================================
-- 125 — أسعار واتساب بالدولار من بطاقة أسعار Meta لمصر (سارية 1 أكتوبر 2026)
--
-- المشكلة: الأسعار المخصومة كانت أرقامًا مكتوبة يدويًا بالجنيه بلا مصدر:
--   template_charge_egp = 0.282  (مرافق 0.032 + مصاريف 0.25)
--   text_charge_egp     = 0      (رسائل الخدمة بلا سعر أصلًا)
-- بينما Meta تسعّر بالدولار أصلًا، وغيّرت أسعارها في 1 أكتوبر 2026، وبدأت
-- من التاريخ نفسه فوترة رسائل الخدمة بعد أول 1,000 رسالة مجانية شهريًا
-- لكل رقم. السعر القديم كان أقل من تكلفة Meta نفسها (تسويق 0.39 ج.م مقابل
-- تكلفة ميتا ~3.50 ج.م) — أي خصم بأقل من التكلفة.
--
-- المصدر (رُوجع من صفحة Meta الرسمية وملف بطاقة الأسعار PDF في 2026-11-23):
--   Meta for Developers — "Pricing on the WhatsApp Business Platform"
--   بطاقة أسعار USD سارية 1 أكتوبر 2026، مصر سوق مستقل (EG +20):
--     Marketing 0.0644 / Utility 0.0036 / Authentication 0.0036
--     Service 0.0036 / Authentication-international 0.0650 دولار للرسالة.
--   https://developers.facebook.com/documentation/business-messaging/whatsapp/pricing
--
-- القرار (بطلب مالك المشروع 2026-11-23): الأسعار تُحفظ بالدولار كما هي من
-- Meta، بلا مصاريف مدعوم وبلا سعر صرف ثابت في أي ملف. الجنيه يُحسب وقت
-- المحاسبة فقط: سعر الدولار × سعر صرف البنك المركزي الحي، عبر دالة
-- fx-rate (supabase/functions/fx-rate — البنك المركزي أولًا، ثم
-- Frankfurter، ثم ذاكرة fx_rates؛ الترحيل 126). لذلك هذا الترحيل يثبّت
-- مفتاحين بالدولار فقط:
--   template_charge_usd = 0.0036  (قالب — يتبع سعر المرافق، انظر أدناه)
--   text_charge_usd     = 0.0036  (نصية/خدمة بعد الشريحة المجانية)
-- المفتاحان القديمتان بالجنيه (template_charge_egp/text_charge_egp) تُتركان
-- كما هما في قاعدة البيانات — لا يقرؤهما أي كود بعد هذا التغيير، وحذفهما
-- قد يكسر مستهلكًا خارج المستودع؛ إزالتهما قرار تنظيف لاحق منفصل.
--
-- لماذا سعر القالب موحَّد؟ مسارا send-whatsapp وMCP يخصمان سعرًا ثابتًا
-- واحدًا لكل قالب لأنهم لا يعرفون فئة القالب وقت الخصم (لا يوجد جدول
-- قوالب بفئاته). السعر الموحَّد يتبع سعر المرافق. قوالب التسويق تُخصم بهذا
-- السعر الموحَّد أيضًا — أي أقل من تكلفتها الحقيقية (0.0644 دولار) — وهو
-- قيد معروف من قبل، لا يغيّره هذا الترحيل. التسعير الدقيق حسب الفئة يعمل
-- في مسار المتصفح (services/wallet-pricing.js في whatsapp-mad3oom).
--
-- ماذا عن رسائل الخدمة؟ text_charge_usd = 0.0036 هو السعر بعد الشريحة
-- المجانية فقط. البوابة نفسها (أول 1,000 رسالة خدمة مسلَّمة شهريًا لكل
-- رقم مجانًا، ثم يُحاسَب من الرسالة 1,001) تعيش في
-- whatsapp-billing.ts‏ (resolveServiceCharge) — فالقيمة هنا بلا أثر
-- قبل نفاد الشريحة.
--
-- الشرائح الحجمية (volume tiers) لا تُطبَّق: تبدأ من 100,001 رسالة مرافق
-- شهريًا، وحجم مدعوم أقل من ذلك بكثير.
--
-- ⚠️ أثر تجاري: هذا الترحيل يغيّر ما يُخصم فعليًا من محافظ العملاء فور
-- تطبيقه (القالب كان 0.282 ج.م ثابتة، والنصية كانت 0؛ بعده: سعر الدولار
-- × سعر الصرف الحي وقت الإرسال). تطبيقه حيًا هو قرار إطلاق تجاري يحتاج
-- موافقة صريحة من مالك المشروع — ملف الترحيل وحده لا يُطلقه.
--
-- المتطلبات: لا شيء (upsert بالمفتاح).
-- التراجع: حذف المفتاحين بالدولار (انظر _rollback/125_*.down.sql)؛
-- المفتاحان بالجنيه لم يمسّهما هذا الترحيل أصلًا.
-- ============================================================================

insert into public.integration_settings (key, value)
values ('template_charge_usd', '0.0036'::jsonb)
on conflict (key) do update set value = excluded.value;

insert into public.integration_settings (key, value)
values ('text_charge_usd', '0.0036'::jsonb)
on conflict (key) do update set value = excluded.value;

-- ============================================================================
-- تحقق ذاتي: القيمتان الجديدتان مخزَّنتان بالدولار.
-- ============================================================================
do $$
declare
  v_template numeric;
  v_text numeric;
begin
  select (value::text)::numeric into v_template
  from public.integration_settings where key = 'template_charge_usd';
  select (value::text)::numeric into v_text
  from public.integration_settings where key = 'text_charge_usd';
  if v_template is distinct from 0.0036 or v_text is distinct from 0.0036 then
    raise exception '125: template_charge_usd=% text_charge_usd=% (المتوقع 0.0036)', v_template, v_text;
  end if;
end $$;
