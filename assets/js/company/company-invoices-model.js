/**
 * company-invoices-model.js — سجل فواتير الشركة: ما مصدره، وما الذي لا نعرضه.
 *
 * ── ما وُجد فعلًا (لا افتراض) ─────────────────────────────────────────────
 *
 * جدول الفواتير هو public.accounting_invoices (الترحيل 005):
 *   external_invoice_id, invoice_number, ticket_id, user_id, subscription_id،
 *   plan, billing_cycle, subtotal, tax_amount, total, currency،
 *   issue_date, due_date, status, public_token, reply_id, attachment_id.
 *
 * لا يوجد فيه عمود company_id ولا أي رابط إلى شركة — والربط الوحيد الممكن هو
 * عبر ticket_id (تذكرة طلب الاشتراك) أو user_id (الحساب الفردي الذي اشترى).
 * تُملأ الصفوف من مزامنة نظام محاسبي خارجي عبر record_accounting_invoice()
 * بمفتاح service_role، ولا يوجد التزام موثّق بأن كل اشتراك تنتج عنه فاتورة.
 *
 * وسياسة القراءة own_invoices_select تسمح بـ user_id = auth.uid() أو
 * admin/super_user فقط — فعضو الشركة غير المالك لا يرى فواتير الشركة أصلًا،
 * والمالك يرى فواتيره الفردية لا «فواتير الشركة» ككيان.
 *
 * وحمولة اللوحة نفسها لا تساعد: get_my_company_dashboard() (الترحيل 016)
 * ترجع صفوف الاشتراكات بلا ticket_id ولا ticket_number، فلا يمكن ربط اشتراك
 * بتذكرته من الواجهة. والترحيل 111 يصرّح بأن تذكرة الشركة «بلا فاتورة» —
 * الفاتورة تُرفق داخل تذكرة طلب الاشتراك مع مدعوم (scope='mad3oom_support')
 * لا داخل تذاكر نطاق الشركة.
 *
 * النتيجة: لا يوجد مصدر موثوق لقائمة فواتير على مستوى الشركة. نعرض حالة
 * فراغ صريحة تربط الفواتير بتذاكر طلبات الاشتراك كما هو الوضع الحالي،
 * برابط إلى قسم التذاكر مع مدعوم حيث تعيش تلك التذاكر — ولا نخترع سجلًا.
 *
 * ── قيد الدفع بـ Pi ──────────────────────────────────────────────────────
 *
 * الموضع الحالي للقيد هو خطوة الدفع وحدها في subscriptions-script.js:
 *   :736 في وضع Pi مع حساب شركة، و:754 عند اختيار Pi في مودال الدفع لحساب
 *   شركة — وفي الحالتين تنبيه «الدفع بـPi متاح للحسابات الفردية حاليًا».
 *   فعميل الشركة لا يعلم بالقيد إلا بعد وصوله لخطوة الدفع.
 * النص هنا هو نفسه المعروض مبكرًا في قسم الاشتراكات باللوحة، قبل ذلك.
 */

/**
 * حكم المصدر: هل توجد قائمة فواتير موثوقة على مستوى الشركة؟
 * مجمّد — لا يُبنى سجل من صفوف لا رابط شركويًا فيها.
 */
export const COMPANY_INVOICE_SOURCE = Object.freeze({
    available: false,
    table: 'accounting_invoices',
    /** الأعمدة التي يمكن أن تربط فاتورة بطلب اشتراك — ولا واحد منها يربطها بشركة. */
    linkColumns: Object.freeze(['ticket_id', 'user_id', 'subscription_id']),
    /** لا عمود company_id في الجدول (005) ولا فهرس عليه. */
    hasCompanyColumn: false,
    /** حمولة اللوحة (016) بلا ticket_id/ticket_number فلا ربط اشتراك↔تذكرة من الواجهة. */
    dashboardCarriesTicketLink: false,
    /** سياسة القراءة فردية (user_id = auth.uid()) — عضو الشركة غير المالك لا يرى شيئًا. */
    readPolicy: 'own_invoices_select',
    /** موطن الفاتورة الفعلي كما هو اليوم: مرفقة داخل تذكرة طلب الاشتراك مع مدعوم. */
    invoiceHome: 'subscription_request_ticket'
});

export function resolveCompanyInvoiceSource() {
    return COMPANY_INVOICE_SOURCE;
}

